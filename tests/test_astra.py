# -*- coding: utf-8 -*-
"""GPT-6 Astra: поколение, его правила и детектор пишущих задач.

Astra вышла 3 сентября 2026 и ведёт себя иначе предшественников в двух местах,
которые видны прямо в тексте промпта: она чаще останавливается и спрашивает
вместо того, чтобы делать, и у неё есть опубликованный вендором блоклист
слов-маркеров для прозы. Обе вещи лечатся строкой в промпте, значит это наша
работа, а не вопрос рантайм-параметров.
"""

import json
import os
import re

import pytest

from nativeprompt.analyze import analyze, task_shape
from nativeprompt.detect import resolve
from nativeprompt.explain import build_report

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПРАВИЛА = json.load(open(os.path.join(КОРЕНЬ, "nativeprompt", "rules", "openai.json"),
                         encoding="utf-8"))


def ids(промпт, модель="gpt-6-astra"):
    return {f["id"] for f in analyze(промпт, resolve(модель))}


# ── поколение ───────────────────────────────────────────────────────────
@pytest.mark.parametrize("что_ввели", [
    "gpt-6-astra", "gpt-6", "gpt6", "astra", "GPT-6-Astra", "openai/gpt-6-astra",
])
def test_поколение_astra_опознаётся(что_ввели):
    """Человек пишет модель как придётся: из документации, из конфига, на слух."""
    t = resolve(что_ввели)
    assert t["family"] == "openai", "%s ушло не в openai: %s" % (что_ввели, t)
    assert t["generation"] == "gpt-6-astra", (
        "%s не опознано как astra, получили %r" % (что_ввели, t.get("generation")))


def test_у_поколения_есть_ссылка_на_свой_гайд():
    g = ПРАВИЛА["generations"]["gpt-6-astra"]
    assert g["doc"].startswith("https://developers.openai.com/"), g
    assert "latest-model" in g["doc"], "ссылка ведёт не на страницу гайда: %s" % g["doc"]


# ── правила поколения ───────────────────────────────────────────────────
ПРАВИЛА_ASTRA = [r for r in ПРАВИЛА["rules"] if r.get("scope") == "gpt-6-astra"]


def test_правила_astra_заведены():
    assert len(ПРАВИЛА_ASTRA) >= 3, "правил под astra почти нет: %s" % [
        r["id"] for r in ПРАВИЛА_ASTRA]


def test_у_каждого_правила_astra_якорь_на_раздел():
    """Ссылка на страницу целиком заставляет искать раздел глазами.

    У гайда Astra разделы адресуются якорями, и правило обязано вести в свой,
    иначе человек открывает длинную страницу и не понимает, что именно читать.
    """
    for r in ПРАВИЛА_ASTRA:
        assert "#" in r["source"], "%s: ссылка без якоря: %s" % (r["id"], r["source"])


def test_бias_к_действию_горит_на_astra_и_молчит_на_предыдущем_поколении():
    """Ключевое отличие: Astra чаще спрашивает вместо того, чтобы делать.

    На gpt-5.6 такого поведения вендор не описывал, и правило там гореть
    не должно — иначе это шум, который стоит человеку контекста на каждом промпте.
    """
    промпт = "поправь верстку на главной"
    assert "astra-bias-to-action" in ids(промпт, "gpt-6-astra")
    assert "astra-bias-to-action" not in ids(промпт, "gpt-5.6")


def test_блоклист_слоп_слов_только_на_пишущих_задачах():
    """Блоклист вендора про прозу. На «почини баг» он мимо."""
    текст = "напиши статью про переход на новую модель, страницы на три"
    код = "почини баг в @src/auth.py, тесты в tests/test_auth.py"
    assert "astra-slop-blocklist" in ids(текст, "gpt-6-astra"), \
        "на пишущей задаче правило не сработало"
    assert "astra-slop-blocklist" not in ids(код, "gpt-6-astra"), \
        "правило про прозу сработало на починке бага"


def test_в_блоклисте_есть_конструкция_противопоставления():
    """Вендор внёс в список ровно ту антитезу, по которой узнают машинный текст.

    Это самая узнаваемая позиция списка, и терять её при переносе в правило
    нельзя: без неё правило превращается в общее «пишите проще».
    """
    r = next(r for r in ПРАВИЛА_ASTRA if r["id"] == "astra-slop-blocklist")
    склеено = (r["why"] + r.get("unless", "")).lower()
    assert "not y" in склеено or "не y" in склеено, (
        "в правиле потеряна конструкция «X, not Y»: %s" % r["why"][:200])


# ── детектор пишущей задачи ─────────────────────────────────────────────
@pytest.mark.parametrize("промпт", [
    "напиши статью про новую модель",
    "составь текст письма клиентам",
    "сделай описание для страницы товара",
    "write a blog post about the release",
    "перепиши этот абзац живее",
])
def test_пишущая_задача_опознаётся(промпт):
    assert "writing_task" in {f["check"] for f in analyze(промпт, resolve("gpt-6-astra"))} \
        or "astra-slop-blocklist" in ids(промпт), "не опознано как пишущая задача: %r" % промпт


@pytest.mark.parametrize("промпт", [
    "почини баг в @src/auth.py",
    "прогони тесты и покажи упавшие",
    "разверни контейнер на стейдже",
    "напиши тест на функцию login",          # «напиши» есть, но предмет код
])
def test_кодовая_задача_не_считается_пишущей(промпт):
    assert "astra-slop-blocklist" not in ids(промпт), "кодовая задача принята за прозу: %r" % промпт


# ── отчёт целиком ───────────────────────────────────────────────────────
def test_отчёт_по_astra_собирается_и_называет_поколение():
    r = build_report("можешь посмотреть, что не так с логином?", "gpt-6-astra")
    assert r["meta"]["generation"] == "gpt-6-astra"
    assert r["improved"], "пустой результат"


def test_версия_правил_openai_поднята_под_astra():
    """Шпаргалка датируется днём сверки с доками, иначе непонятно, что в ней учтено."""
    assert ПРАВИЛА["rules_version"] >= "2026-09-07", (
        "rules_version не обновлён: %s" % ПРАВИЛА["rules_version"])
